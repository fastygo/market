// Command designgen turns the market-design JSON specs (ui8kit/market-design,
// a JS design repo checked out next to this one) into the templ set of the
// storefront: ui/design (blocks, parts and compositions over the UI8Kit
// templ primitives) and ui/styles/generated/design.css (semantic class
// names with @apply, ADR-0029, ADR-0034).
//
//	go run ./scripts/designgen -src ../market-design          # write
//	go run ./scripts/designgen -src ../market-design -check   # fail on drift
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const header = "Code generated by scripts/designgen from ui8kit/market-design specs. DO NOT EDIT."

func main() {
	src := flag.String("src", "../market-design", "market-design checkout")
	out := flag.String("out", "ui/design", "templ package dir")
	cssOut := flag.String("css", "ui/styles/generated/design.css", "semantic CSS output")
	extra := flag.String("icons", "scripts/designgen/icons.txt", "extra Lucide icon names, one per line")
	patchFile := flag.String("patches", "scripts/designgen/patches.json", "SSR patches: spec id -> node name -> props")
	check := flag.Bool("check", false, "fail when the outputs differ")
	flag.Parse()

	specDir := filepath.Join(*src, "packages/specs")
	tsrc, err := os.ReadFile(filepath.Join(specDir, "src/types.ts"))
	must(err)
	loadTypes(string(tsrc))

	g := &gen{specs: map[string]*Spec{}, cssSeen: map[string]string{}, icons: map[string]bool{}}
	if b, err := os.ReadFile(*patchFile); err == nil {
		must(json.Unmarshal(b, &g.patches))
	}
	extraProps := map[string]map[string]PropDecl{}
	for id, nodes := range g.patches {
		if ps, ok := nodes["$props"]; ok {
			b, _ := json.Marshal(ps)
			var decl map[string]PropDecl
			must(json.Unmarshal(b, &decl))
			extraProps[id] = decl
		}
	}
	var comps, blocks []*Spec
	for _, dir := range []string{"compose", "blocks"} {
		files, _ := filepath.Glob(filepath.Join(specDir, "json", dir, "*.json"))
		sort.Strings(files)
		for _, f := range files {
			b, err := os.ReadFile(f)
			must(err)
			var s Spec
			must(json.Unmarshal(b, &s))
			s.file = f
			for k, d := range extraProps[s.ID] {
				if s.Props == nil {
					s.Props = map[string]PropDecl{}
				}
				s.Props[k] = d
			}
			g.specs[s.Name] = &s
			if s.Kind == "composition" {
				comps = append(comps, &s)
			} else {
				blocks = append(blocks, &s)
			}
		}
	}
	files := map[string]string{}
	files["compose.templ"] = g.emitCompositions(comps)
	var failed []string
	for _, s := range blocks {
		if skip[s.ID] {
			continue
		}
		code, err := g.emitBlock(s)
		if err != nil {
			failed = append(failed, err.Error())
			continue
		}
		files[strings.TrimPrefix(strings.TrimPrefix(s.ID, "block."), "part.")+".templ"] = code
	}
	if len(failed) > 0 {
		fmt.Fprintln(os.Stderr, "designgen: failed specs:\n  "+strings.Join(failed, "\n  "))
		os.Exit(1)
	}
	files["types.go"] = mustFmt(emitTypes())
	files["helpers.go"] = mustFmt(helpers)
	if b, err := os.ReadFile(*extra); err == nil {
		for _, l := range strings.Split(string(b), "\n") {
			if l = strings.TrimSpace(l); l != "" && !strings.HasPrefix(l, "#") {
				g.icons[l] = true
			}
		}
	}
	files["icons.go"] = mustFmt(emitIcons(*src, g.icons))
	css := emitCSS(g.css)

	drift := false
	write := func(path, content string) {
		old, _ := os.ReadFile(path)
		if string(old) == content {
			return
		}
		if *check {
			fmt.Fprintln(os.Stderr, "designgen: stale "+path)
			drift = true
			return
		}
		must(os.MkdirAll(filepath.Dir(path), 0o755))
		must(os.WriteFile(path, []byte(content), 0o644))
	}
	for _, name := range sortedKeys(files) {
		write(filepath.Join(*out, name), files[name])
	}
	write(*cssOut, css)
	// remove generated files of specs that are gone
	existing, _ := filepath.Glob(filepath.Join(*out, "*.templ"))
	for _, f := range existing {
		if _, ok := files[filepath.Base(f)]; !ok {
			if *check {
				fmt.Fprintln(os.Stderr, "designgen: orphan "+f)
				drift = true
			} else {
				_ = os.Remove(f)
				_ = os.Remove(strings.TrimSuffix(f, ".templ") + "_templ.go")
			}
		}
	}
	if drift {
		os.Exit(1)
	}
	fmt.Printf("designgen: %d compositions, %d blocks, %d classes, %d icons\n", len(comps), len(files)-4, len(g.css), len(g.icons))
}

// skip lists design-system-only blocks (the UI kit page of market-design).
var skip = map[string]bool{"block.token-grid": true, "block.type-specimen": true, "block.system-header": true, "block.system-footer": true}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "designgen:", err)
		os.Exit(1)
	}
}

func mustFmt(s string) string {
	b, err := format.Source([]byte(s))
	if err != nil {
		fmt.Fprintln(os.Stderr, s)
		must(err)
	}
	return string(b)
}

func emitCSS(rules []cssRule) string {
	var b bytes.Buffer
	b.WriteString("/* " + header + " */\n")
	b.WriteString("/* Semantic classes of the design kit (ADR-0029, ADR-0034): mk-* compositions, <block>-<part> blocks. */\n")
	b.WriteString("/* Sublayers: kit (mk-* runtime recipes) < blocks (one class per element; identical rules share a selector) < state (conditional classes). */\n")
	b.WriteString("@layer components {\n  @layer design {\n    @layer kit, blocks, state;\n")
	for _, layer := range []string{"kit", "blocks", "state"} {
		fmt.Fprintf(&b, "    @layer %s {\n", layer)
		var order []string
		sel := map[string][]string{}
		for _, r := range rules {
			if r.layer != layer {
				continue
			}
			if _, ok := sel[r.apply]; !ok {
				order = append(order, r.apply)
			}
			sel[r.apply] = append(sel[r.apply], "."+r.name)
		}
		for _, a := range order {
			fmt.Fprintf(&b, "      %s { @apply %s; }\n", strings.Join(sel[a], ", "), a)
		}
		b.WriteString("    }\n")
	}
	b.WriteString("  }\n}\n")
	return b.String()
}

func emitIcons(src string, used map[string]bool) string {
	raw, err := os.ReadFile(filepath.Join(src, "node_modules/lucide-static/icon-nodes.json"))
	must(err)
	var all map[string][][2]any
	must(json.Unmarshal(raw, &all))
	var b strings.Builder
	b.WriteString("// " + header + "\n// Lucide glyphs (ISC, https://lucide.dev) used by the blocks and screens.\n\npackage design\n\n")
	b.WriteString("var glyphs = map[string]string{\n")
	for _, name := range sortedKeys(used) {
		nodes, ok := all[name]
		if !ok {
			fmt.Fprintln(os.Stderr, "designgen: unknown icon "+name)
			os.Exit(1)
		}
		var s strings.Builder
		for _, n := range nodes {
			tag := n[0].(string)
			attrs := n[1].(map[string]any)
			s.WriteString("<" + tag)
			for _, k := range sortedKeys(attrs) {
				fmt.Fprintf(&s, ` %s="%v"`, k, attrs[k])
			}
			s.WriteString("></" + tag + ">")
		}
		fmt.Fprintf(&b, "\t%q: %q,\n", name, s.String())
	}
	b.WriteString("}\n")
	return b.String()
}
